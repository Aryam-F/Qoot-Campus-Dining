void showRatingDialog(BuildContext context, MenuItem item) {
  int selectedStars = 5;
  showDialog(
    context: context,
    builder: (dialogContext) => StatefulBuilder(
      builder: (dialogContext, setDialogState) {
        return AlertDialog(
          title: Text('Rate ${item.name}'),
          content: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              const Text('Tap a star to give your score:'),
              const SizedBox(height: 4),
              const Text(
                'You can change your rating later; each device counts once.',
                style: TextStyle(fontSize: 11, color: Colors.grey),
                textAlign: TextAlign.center,
              ),
              const SizedBox(height: 12),
              Row(
                mainAxisAlignment: MainAxisAlignment.center,
                children: List.generate(5, (index) {
                  return IconButton(
                    icon: Icon(
                      index < selectedStars ? Icons.star : Icons.star_border,
                      color: Colors.amber,
                      size: 30,
                    ),
                    onPressed: () =>
                        setDialogState(() => selectedStars = index + 1),
                  );
                }),
              ),
            ],
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(dialogContext),
              child: const Text('Cancel'),
            ),
            ElevatedButton(
              style: ElevatedButton.styleFrom(backgroundColor: kGreen),
              onPressed: () async {
                final messenger = ScaffoldMessenger.of(context);
                Navigator.pop(dialogContext);
                final err = await store.rateItem(item, selectedStars);
                messenger.showSnackBar(
                  SnackBar(content: Text(err ?? 'Your rating has been saved!')),
                );
              },
              child: const Text(
                'Submit Rating',
                style: TextStyle(color: Colors.white),
              ),
            ),
          ],
        );
      },
    ),
  );
}

