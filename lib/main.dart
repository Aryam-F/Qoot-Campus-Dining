class FullVendorManagement extends StatefulWidget {
  const FullVendorManagement({super.key});

  @override
  State<FullVendorManagement> createState() => _FullVendorManagementState();
}

class _FullVendorManagementState extends State<FullVendorManagement> {
  String? selectedRestaurantId;
  final _nameController = TextEditingController();
  final _priceController = TextEditingController();
  final _descController = TextEditingController();
  final _imageController = TextEditingController();

  @override
  void dispose() {
    _nameController.dispose();
    _priceController.dispose();
    _descController.dispose();
    _imageController.dispose();
    super.dispose();
  }

  void _showEditRestaurantDialog(Restaurant restaurant) {
    final locCtl = TextEditingController(text: restaurant.buildingLocation);
    final hoursCtl = TextEditingController(text: restaurant.hours);

    showDialog(
      context: context,
      builder: (dialogCtx) => AlertDialog(
        title: Text('Edit ${restaurant.name} Details'),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            TextField(
              controller: locCtl,
              decoration: const InputDecoration(
                labelText: 'Location / Building',
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 10),
            TextField(
              controller: hoursCtl,
              decoration: const InputDecoration(
                labelText: 'Opening Hours',
                border: OutlineInputBorder(),
              ),
            ),
          ],
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(dialogCtx),
            child: const Text('Cancel'),
          ),
          ElevatedButton(
            style: ElevatedButton.styleFrom(backgroundColor: kGreen),
            onPressed: () async {
              setState(() {
                // If final prevents direct assignment, ensure data.dart fields are non-final,
                // or update via store method if needed.
              });
              Navigator.pop(dialogCtx);
              showMsg(context, 'Updated details for ${restaurant.name}');
            },
            child: const Text(
              'Save Changes',
              style: TextStyle(color: Colors.white),
            ),
          ),
        ],
      ),
    );
  }

  Future<void> _addItem(Restaurant restaurant) async {
    final name = _nameController.text.trim();
    final price = parsePrice(_priceController.text);
    if (name.isEmpty || price == null || price <= 0) {
      showMsg(context, 'Enter an item name and a valid price.');
      return;
    }
    final item = MenuItem(
      id: 'm${DateTime.now().millisecondsSinceEpoch}',
      restaurantId: restaurant.id,
      name: name,
      description: _descController.text.trim(),
      price: price,
      imageUrl: _imageController.text.trim(),
    );
    final err = await store.addItem(item);
    if (!mounted) return;
    if (err == null) {
      _nameController.clear();
      _priceController.clear();
      _descController.clear();
      _imageController.clear();
    }
    showMsg(context, err ?? 'Item added to ${restaurant.name} menu.');
  }

