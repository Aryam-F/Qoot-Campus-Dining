Future<void> openGoogleMaps(double lat, double lng, String label) async {
  final Uri url = Uri.parse(
    'https://www.google.com/maps/dir/?api=1&destination=$lat,$lng&travelmode=walking',
  );
  if (await canLaunchUrl(url)) {
    await launchUrl(url, mode: LaunchMode.externalApplication);
  }
}

double? parsePrice(String text) =>
    double.tryParse(text.trim().replaceAll(',', '.'));

Color crowdColor(CrowdLevel l) {
  switch (l) {
    case CrowdLevel.low:
      return Colors.green;
    case CrowdLevel.medium:
      return Colors.orange;
    case CrowdLevel.high:
      return Colors.red;
  }
}

String crowdLabel(CrowdLevel l) {
  switch (l) {
    case CrowdLevel.low:
      return 'Low';
    case CrowdLevel.medium:
      return 'Medium';
    case CrowdLevel.high:
      return 'High';
  }
}

void showMsg(BuildContext context, String text) {
  ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(text)));
}

class MenuItemImage extends StatelessWidget {
  final String url;
  final double size;
  const MenuItemImage({super.key, required this.url, this.size = 60});

  @override
  Widget build(BuildContext context) {
    final placeholder = Container(
      width: size,
      height: size,
      color: const Color(0xFFE0F2F1),
      child: Icon(Icons.fastfood, color: kGreen, size: size * 0.5),
    );
    return ClipRRect(
      borderRadius: BorderRadius.circular(6),
      child: url.trim().isEmpty
          ? placeholder
          : Image.network(
              url.trim(),
              width: size,
              height: size,
              fit: BoxFit.cover,
              errorBuilder: (context, error, stackTrace) => placeholder,
            ),
    );
  }
}

class StoreGate extends StatelessWidget {
  final Widget Function(BuildContext) builder;
  const StoreGate({super.key, required this.builder});

  @override
  Widget build(BuildContext context) {
    return ListenableBuilder(
      listenable: store,
      builder: (context, _) {
        if (store.error != null && !store.loaded) {
          return Center(
            child: Padding(
              padding: const EdgeInsets.all(24),
              child: Text(
                'Could not load data from Firebase.\n${store.error}',
                textAlign: TextAlign.center,
              ),
            ),
          );
        }
        if (!store.loaded) {
          return const Center(child: CircularProgressIndicator());
        }
        return builder(context);
      },
    );
  }
}

