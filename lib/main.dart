  Widget build(BuildContext context) {
    return StoreGate(
      builder: (context) {
        if (store.restaurants.isEmpty) {
          return const Center(child: Text('No restaurants found.'));
        }
        final restaurant =
            store.restaurantById(selectedRestaurantId ?? '') ??
            store.restaurants.first;
        final menu = store.menuOf(restaurant.id);

        return ListView(
          padding: const EdgeInsets.all(16.0),
          children: [
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                const Text(
                  'Select Cafe / Restaurant:',
                  style: TextStyle(fontSize: 13, fontWeight: FontWeight.bold),
                ),
                ElevatedButton.icon(
                  style: ElevatedButton.styleFrom(backgroundColor: kGreen),
                  icon: const Icon(
                    Icons.edit_location,
                    size: 16,
                    color: Colors.white,
                  ),
                  label: const Text(
                    'Edit Cafe Info',
                    style: TextStyle(color: Colors.white, fontSize: 11),
                  ),
                  onPressed: () => _showEditRestaurantDialog(restaurant),
                ),
              ],
            ),
            const SizedBox(height: 6),
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 12),
              decoration: BoxDecoration(
                border: Border.all(color: Colors.grey),
                borderRadius: BorderRadius.circular(8),
              ),
              child: DropdownButtonHideUnderline(
                child: DropdownButton<String>(
                  value: restaurant.id,
                  isExpanded: true,
                  items: store.restaurants.map((res) {
                    return DropdownMenuItem<String>(
                      value: res.id,
                      child: Text(
                        res.name,
                        style: const TextStyle(fontWeight: FontWeight.bold),
                      ),
                    );
                  }).toList(),
                  onChanged: (id) {
                    if (id != null) setState(() => selectedRestaurantId = id);
                  },
                ),
              ),
            ),
            const SizedBox(height: 16),
            Text(
              'Add New Item to ${restaurant.name}',
              style: const TextStyle(
                fontSize: 14,
                fontWeight: FontWeight.bold,
                color: kGreen,
              ),
            ),
            const SizedBox(height: 10),
            TextField(
              controller: _nameController,
              decoration: const InputDecoration(
                labelText: 'Item Name',
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 10),
            TextField(
              controller: _priceController,
              keyboardType: const TextInputType.numberWithOptions(
                decimal: true,
              ),
              decoration: const InputDecoration(
                labelText: 'Price (SAR)',
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 10),
            TextField(
              controller: _descController,
              decoration: const InputDecoration(
                labelText: 'Description',
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 10),
            TextField(
              controller: _imageController,
              decoration: const InputDecoration(
                labelText: 'Image URL',
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 10),
            ElevatedButton(
              style: ElevatedButton.styleFrom(
                backgroundColor: kGreen,
                minimumSize: const Size(double.infinity, 45),
              ),
              onPressed: () => _addItem(restaurant),
              child: const Text(
                'Add Item to Menu',
                style: TextStyle(
                  color: Colors.white,
                  fontWeight: FontWeight.bold,
                ),
              ),
            ),
            const SizedBox(height: 16),
            Text(
              'Current Menu Items (${menu.length}):',
              style: const TextStyle(fontWeight: FontWeight.bold),
            ),
            for (final item in menu)
              ListTile(
                contentPadding: EdgeInsets.zero,
                leading: MenuItemImage(url: item.imageUrl, size: 44),
                title: Text(item.name),
                subtitle: Text('${item.price} SAR'),
                trailing: Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    IconButton(
                      icon: const Icon(Icons.delete, color: Colors.red),
                      onPressed: () async {
                        final err = await store.deleteItem(item);
                        if (!mounted) return;
                        if (err != null) showMsg(context, err);
                      },
                    ),
                  ],
                ),
              ),
          ],
        );
      },
    );
  }
